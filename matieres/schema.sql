-- =====================================================================
--  Utilisation Matières — schéma à coller dans le SQL Editor de Supabase
--  (MÊME projet que reservation-machines / impression 3D / commandes : ggmlfbxppgeivfvlxxrj)
--
--  Ce script AJOUTE 10 tables (préfixe mat_). Il ne supprime ni ne modifie
--  aucune donnée ni aucune table existante. Relançable sans risque (IF NOT EXISTS).
--
--  Sécurité : lecture publique, écritures uniquement via l'Edge Function matiere-op (voir README.md).
