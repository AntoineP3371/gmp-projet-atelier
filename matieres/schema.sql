-- ---------- Sécurité (RLS) — lecture publique, écritures via Edge Function ----------
-- Le public LIT les tables mat_* ; toutes les ÉCRITURES passent par l'Edge Function « matiere-op »
-- (clé service, qui contourne la RLS, droits vérifiés côté serveur). Aucune policy INSERT/UPDATE/DELETE
-- = refus total pour la clé anon. (Déployer matiere-op AVANT de s'en servir : voir README.)
