-- ---------- Matières (gérées par l'admin) ----------------------------
create table if not exists public.mat_matieres (
  nom        text primary key,                 -- ex. "Acier S235", "Aluminium 6060"
  densite    numeric not null default 7.85,    -- kg/dm³  (acier 7.85 · alu 2.70 · inox 7.9…)
  prix_kg    numeric,                          -- prix tel que saisi par l'admin (null = pas encore renseigné)
  prix_mode  text not null default 'ttc',      -- 'ttc' | 'ht' — le prix est TOUJOURS affiché/utilisé en TTC
  actif      boolean not null default true,
  maj_at     timestamptz not null default now()
);
alter table public.mat_matieres add column if not exists prix_mode text not null default 'ttc';

-- ---------- Fournisseurs (gérés par l'admin) ---------------------------
create table if not exists public.mat_fournisseurs (
  nom        text primary key,                 -- ex. "Letoile", "Almet", "EMSO"
  actif      boolean not null default true,
  maj_at     timestamptz not null default now()
);

-- ---------- Familles (gérées par l'admin) ------------------------------
-- Regroupement de haut niveau des formes, tel que l'organigramme de l'atelier
-- l'utilise pour savoir quel fournisseur livre quoi (ex. "Tôles", "Barres", "Profilés").
create table if not exists public.mat_familles (
  nom        text primary key,
  actif      boolean not null default true,
  maj_at     timestamptz not null default now()
);

-- ---------- Formes (gérées par l'admin) -------------------------------
-- 'type' = type géométrique connu de l'appli (elle en déduit la formule de section) :
--   plat | rond | carre | tube_rond | tube_carre | tube_carre_eq | L | T | U | I | tole
-- 'famille' = regroupement (mat_familles.nom), sert à filtrer les formes proposées
-- à l'étudiant une fois la matière et la famille choisies.
create table if not exists public.mat_formes (
  nom        text primary key,                 -- ex. "Pavé (plat)", "Cylindre plein", "Profilé en I"
  type       text not null default 'plat',
  famille    text,
  actif      boolean not null default true,
  maj_at     timestamptz not null default now()
);
alter table public.mat_formes add column if not exists famille text;

-- ---------- Associations matière → fournisseur → famille (gérées par l'admin) --
-- Encode l'organigramme « quelle matière, livrée par quel fournisseur, pour quelle
-- famille » : ex. (Aluminium, EMSO, Barres), (Aluminium, Almet, Tôles ou Profilés).
-- Le fournisseur n'est jamais demandé à l'étudiant : déduit automatiquement de
-- (matière, famille) côté client (voir fournisseurFor() dans index.html).
create table if not exists public.mat_four_familles (
  id           bigint generated by default as identity primary key,
  fournisseur  text not null,
  matiere      text not null,
  famille      text not null,
  maj_at       timestamptz not null default now(),
  unique(fournisseur, matiere, famille)
);

-- ---------- Bruts proposés (section + longueur standard, par matière) ---
create table if not exists public.mat_bruts (
  id         bigint generated by default as identity primary key,
  matiere    text not null,
  forme      text not null,
  dims       jsonb not null default '{}'::jsonb,   -- ex. {"d":30} ou {"l":40,"e":10}
  longueur   numeric not null,                     -- longueur standard du brut, en mm
  masse_lin  numeric,                              -- kg/m facultatif (sinon calculé : section × densité)
  chute_min  numeric,                              -- colonne conservée mais plus modifiable depuis l'admin (simplifié) ;
                                                     -- le calcul utilise un seuil fixe de 100 mm (reste en dessous = perdu)
  actif      boolean not null default true,
  maj_at     timestamptz not null default now()
);
create index if not exists mat_bruts_mf_idx on public.mat_bruts (matiere, forme);

-- ---------- Dates de commande proposées par l'admin ---------------------
create table if not exists public.mat_dates (
  id            bigint generated by default as identity primary key,
  date_commande date not null,
  note          text default '',
  maj_at        timestamptz not null default now()
);

-- ---------- Budgets matière par parcours (distincts des composants) ------
create table if not exists public.mat_budgets (
  parcours   text primary key,
  limite     numeric,                          -- € pour l'année universitaire (null = pas de limite)
  maj_at     timestamptz not null default now()
);

-- ---------- Paramètres généraux ------------------------------------------
--   trait_scie    : épaisseur perdue à chaque coupe (mm) — reste de brut toujours considéré perdu
--                   (plus de notion de « reste réutilisable », simplifié depuis l'admin)
--   tva_taux      : taux de TVA (%) utilisé pour convertir un prix matière saisi HT en TTC
--   tole_longueur / tole_largeur : format standard d'une tôle (mm)
create table if not exists public.mat_parametres (
  cle        text primary key,
  valeur     text not null default '',
  maj_at     timestamptz not null default now()
);

-- ---------- Demandes de matière -------------------------------------------
create table if not exists public.mat_demandes (
  id                   bigint generated by default as identity primary key,
  created_at           timestamptz not null default now(),
  numero               integer default 0,             -- n° incrémental par projet

  -- Contexte (étudiant)
  projet               text not null default '',
  parcours             text not null default '',
  formation            text not null default '',
  etudiant_nom         text not null default '',
  etudiant_prenom      text not null default '',

  -- Pièce demandée
  matiere              text not null default '',
  famille              text default '',               -- Tôles | Barres | Profilés (ou vide si non déterminé)
  fournisseur          text default '',                -- déduit automatiquement de (matière, famille)
  forme                text not null default '',
  forme_type           text not null default '',
  dims                 jsonb not null default '{}'::jsonb,
  dims_libelle         text default '',               -- ex. "Ø30"
  longueur             numeric,                       -- mm, par pièce (longueur découpée)
  largeur              numeric,                       -- mm, uniquement pour une tôle (largeur découpée)
  quantite             integer not null default 1,
  hors_catalogue       boolean not null default false,
  notes                text default '',               -- usage / précisions de l'étudiant
  precision_etudiant   text default '',               -- précisions ajoutées après une mise en attente

  -- Instantané de l'estimation (les prix peuvent changer ensuite)
  densite              numeric,
  prix_kg              numeric,
  masse_lin            numeric,
  poids_kg             numeric,                       -- poids total des pièces
  cout_matiere         numeric,                       -- € de matière utilisée (= ce qui est débité du budget)
  brut_desc            text default '',               -- ex. "Acier S235 · Cylindre plein Ø30 · 3000 mm"
  brut_longueur        numeric,
  brut_qte             integer default 1,
  part_brut            numeric,                       -- portion du brut utilisée (0–1)
  perdu_mm             numeric,                       -- longueur perdue (trait de scie + chute inutilisable)
  cout_perte           numeric,                       -- € de matière perdue (information)
  reste_mm             numeric,                       -- reste de brut

  -- Décision encadrant
  statut               text not null default 'en_attente',
    -- en_attente | attente_info | validee | commandee | recue | remise | refusee | annulee
  decision             text,                          -- 'stock' (dispo, réservée atelier) | 'commande' (à commander)
  date_commande        date,                          -- date de commande retenue (si decision = 'commande')
  encadrant_nom        text default '',
  encadrant_at         timestamptz,
  encadrant_commentaire text default '',
  encadrant_commentaire_at timestamptz,

  -- Suivi (géré par le gestionnaire)
  gest_nom             text default '',
  gest_commentaire     text default '',
  commandee_at         timestamptz,
  recue_at             timestamptz,
  remise_at            timestamptz,
  statut_at            timestamptz default now(),

  historique           jsonb not null default '[]'::jsonb   -- [{t, statut, par}]
);
create index if not exists mat_demandes_statut_idx on public.mat_demandes (statut);
create index if not exists mat_demandes_projet_idx on public.mat_demandes (lower(projet));
create index if not exists mat_demandes_created_idx on public.mat_demandes (created_at);

-- ---------- Valeurs de départ ----------------------------------------------
